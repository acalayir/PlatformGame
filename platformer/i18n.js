  const STORAGE_KEY = "zipla-ada-lang";

  function normalizeBrowserLang(raw) {
    if (!raw) return null;
    const lower = String(raw).toLowerCase().replace("_", "-");
    const primary = lower.split("-")[0];
    const map = {
      zh: "zh",
      "zh-cn": "zh",
      "zh-tw": "zh",
      "zh-hk": "zh",
      nb: "sv",
      nn: "sv",
      fil: "tl",
      tl: "tl",
      iw: "he",
      in: "id",
      pcm: "ha",
    };
    if (map[lower]) return map[lower];
    if (map[primary]) return map[primary];
    if (T[primary]) return primary;
    return null;
  }

  function detectDefaultLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && T[saved]) return saved;
    } catch (_) {}
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
    return normalizeBrowserLang(nav) || "en";
  }

  let current = detectDefaultLang();

  function setLang(code) {
    if (!T[code]) return current;
    current = code;
    try {
      localStorage.setItem(STORAGE_KEY, code);
    } catch (_) {}
    const meta = LANGS.find((l) => l.code === code);
    document.documentElement.lang = code === "zh" ? "zh-CN" : code;
    document.documentElement.dir = meta && meta.dir === "rtl" ? "rtl" : "ltr";
    return current;
  }

  function t(key, vars) {
    const pack = T[current] || T.en;
    let s = pack[key] != null ? pack[key] : T.en[key] || key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(v));
      }
    }
    return s;
  }

  setLang(current);

  return {
    LANGS,
    STORAGE_KEY,
    getLang: () => current,
    setLang,
    t,
    has: (code) => !!T[code],
  };
